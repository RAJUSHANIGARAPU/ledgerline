import os

from alembic import command
from alembic.config import Config
from alembic.util.exc import AutogenerateDiffsDetected


def test_models_and_migrations_describe_the_same_schema(owner_url):
    cfg = Config(os.path.join(os.path.dirname(__file__), "..", "..", "alembic.ini"))
    cfg.set_main_option("sqlalchemy.url", owner_url)
    try:
        command.check(cfg)
    except AutogenerateDiffsDetected as exc:
        raise AssertionError(f"models and migrations disagree:\n{exc}") from None
